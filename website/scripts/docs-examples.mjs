import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'
import { format, resolveConfig } from 'prettier'

export const exampleFiles = [
  'accessibility',
  'animation',
  'clean_code',
  'counter',
  'custom_elements',
  'data',
  'elements',
  'events',
  'first_window',
  'i18n',
  'installation',
  'interaction_api',
  'layout',
  'mental_model',
  'overlays',
  'platform_roadmap',
  'platform_support',
  'project_structure',
  'styling',
  'tasks',
]

export const root = fileURLToPath(new URL('../../', import.meta.url))
export const output = resolve(root, 'website/app/data/doc-example-sources.generated.ts')

const entries = await Promise.all(
  exampleFiles.map(async (name) => [
    name,
    await readFile(resolve(root, `app_examples/docs-examples/src/examples/${name}.rs`), 'utf8'),
  ]),
)
const generated = await format(
  `// Generated by scripts/docs-examples.mjs from the compiled Rust modules.\nexport const docExampleSources = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const\n`,
  { ...(await resolveConfig(output)), parser: 'typescript' },
)

if (process.argv.includes('--check')) {
  const current = await readFile(output, 'utf8')
  if (current !== generated) throw new Error('Documentation example sources are stale')
} else {
  await writeFile(output, generated)
  console.log(`Generated ${entries.length} exact Rust documentation sources.`)
}
